#!/usr/bin/env python3
"""Generate a host harness that calls the *real* kernel helpers.

Nothing is re-implemented here: the harness `#include`s verbatim copies of

    dv_injection_block_length()
    dv_injection_walk_metadata()
    dv_injection_validate_metadata()
    dv_injection_crc32()
    dv_injection_pkt_type()
    dv_injection_pack_bytes()
    dv_injection_expand_pixels()

taken from the module source that the repository patch adds. Every
`#define DV_INJ_*` and the packet-type enum are copied from the same source as
well, so a constant can never drift away from the kernel again (an earlier
hand-written stub used 595 where the module defines 594).

Only the hardware-facing parts are stubbed out by omission: nothing that the
harness compiles references fb0, canvas, HDMI or the scheduler.

Usage: extract_kernel_harness.py --src dv_injection.c --out harness.c
"""
import argparse
import re
import sys

FUNCS = [
    'dv_injection_block_length',
    'dv_injection_walk_metadata',
    'dv_injection_validate_metadata',
    'dv_injection_crc32',
    'dv_injection_pkt_type',
    'dv_injection_pack_bytes',
    'dv_injection_expand_pixels',
]

MAIN = r'''
/* ---------------- harness entry point (analysis only) ---------------- */
static int hv_read_file(const char *path, unsigned char *buf, size_t cap,
			size_t *len)
{
	FILE *f = fopen(path, "rb");
	size_t n;

	if (!f)
		return -1;
	n = fread(buf, 1, cap, f);
	fclose(f);
	if (n == 0)
		return -1;
	*len = n;
	return 0;
}

int main(int argc, char **argv)
{
	unsigned char dm[DV_INJ_MAX_METADATA_SIZE + 64];
	static unsigned char pkts[DV_INJ_MAX_NUM_HDR_DM_PACKETS]
				[DV_INJ_NUM_BYTES_PER_PACKET];
	static unsigned int pixels[DV_INJ_MAX_NUM_HDR_DM_PACKETS]
				  [DV_INJ_PIXELS_PER_PKT];
	size_t dm_len = 0;
	u8 num_pkts = 0;
	int rc, i;
	char path[4096];
	FILE *f;

	if (argc < 3) {
		fprintf(stderr,
			"usage: %s <dm.bin> <outdir> [strict] [odd] [even] [max_pad]\n",
			argv[0]);
		return 2;
	}
	hv_init_patterns();
	if (argc > 3)
		strict_dm_format = (bool)atoi(argv[3]);
	if (argc > 4)
		odd_pattern = (unsigned int)strtoul(argv[4], NULL, 0);
	if (argc > 5)
		even_pattern = (unsigned int)strtoul(argv[5], NULL, 0);

	if (hv_read_file(argv[1], dm, sizeof(dm), &dm_len)) {
		fprintf(stderr, "cannot read %s\n", argv[1]);
		return 2;
	}

	if (argc > 6) {
		/* Decoder-aux semantics: the reported length may carry the sink
		 * alignment padding, so the walk reports the metadata length and
		 * everything downstream must use it.
		 */
		u32 max_pad = (u32)atoi(argv[6]);
		u32 eff = 0;

		rc = dv_injection_walk_metadata(dm, (u32)dm_len, max_pad, &eff);
		printf("dm_len=%zu max_pad=%u eff=%u validate=%d\n",
		       dm_len, max_pad, eff, rc);
		if (rc)
			return 10;
		dm_len = eff;
	} else {
		rc = dv_injection_validate_metadata(dm, (u32)dm_len);
		printf("dm_len=%zu validate=%d\n", dm_len, rc);
		if (rc)
			return 10;
	}

	rc = dv_injection_pack_bytes(pkts, &num_pkts, dm, (u32)dm_len);
	printf("pack_rc=%d num_pkts=%u\n", rc, num_pkts);
	if (rc)
		return 11;

	snprintf(path, sizeof(path), "%s/packets.bin", argv[2]);
	f = fopen(path, "wb");
	if (!f)
		return 12;
	fwrite(pkts, 1, (size_t)num_pkts * DV_INJ_NUM_BYTES_PER_PACKET, f);
	fclose(f);

	dv_injection_expand_pixels((const u8 (*)[DV_INJ_NUM_BYTES_PER_PACKET])pkts,
				   num_pkts, pixels);
	snprintf(path, sizeof(path), "%s/pixels.bin", argv[2]);
	f = fopen(path, "wb");
	if (!f)
		return 13;
	for (i = 0; i < num_pkts; i++)
		fwrite(pixels[i], sizeof(unsigned int),
		       DV_INJ_PIXELS_PER_PKT, f);
	fclose(f);

	printf("packets_bin=%u pixels_bin=%u packet_bytes=%u pixel_words=%u\n",
	       num_pkts * DV_INJ_NUM_BYTES_PER_PACKET,
	       num_pkts * DV_INJ_PIXELS_PER_PKT * 4,
	       DV_INJ_NUM_BYTES_PER_PACKET, DV_INJ_PIXELS_PER_PKT);
	return 0;
}
'''

PRELUDE = r'''/* Generated by tools/n1/dvhost/extract_kernel_harness.py -- do not edit. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdbool.h>
#include <stdint.h>

typedef uint8_t u8;
typedef uint16_t u16;
typedef uint32_t u32;
typedef int64_t s64;

#ifndef EINVAL
#define EINVAL 22
#endif

/* Kept in sync with the module by copying the source verbatim. */
static bool strict_dm_format;
static unsigned int odd_pattern;
static unsigned int even_pattern;
'''


def grab_define_block(src):
    """Copy every `#define DV_INJ_*`, joining backslash continuations."""
    out = []
    raw = src.splitlines()
    i = 0
    while i < len(raw):
        ln = raw[i]
        if ln.startswith('#define DV_INJ'):
            while ln.rstrip().endswith('\\') and i + 1 < len(raw):
                i += 1
                ln = ln.rstrip()[:-1] + ' ' + raw[i].strip()
            out.append(ln)
        i += 1
    if len(out) < 8:
        raise SystemExit('expected the DV_INJ_* constants in the module source')
    return '\n'.join(out)


def grab_enum(src, name):
    m = re.search(r'^enum %s \{.*?^\};' % re.escape(name), src, re.S | re.M)
    if not m:
        raise SystemExit('enum %s not found' % name)
    return m.group(0)


def grab_function(src, name):
    """Extract a function body by brace matching from its definition."""
    pat = re.compile(r'^[A-Za-z_][A-Za-z0-9_ \t\*]*\b%s\s*\([^;]*?\)\s*\{' % re.escape(name),
                     re.M | re.S)
    m = pat.search(src)
    if not m:
        raise SystemExit('function %s not found' % name)
    start = m.start()
    i = src.index('{', m.end() - 1)
    depth = 0
    while i < len(src):
        c = src[i]
        if c == '{':
            depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0:
                return src[start:i + 1]
        i += 1
    raise SystemExit('unbalanced braces after %s' % name)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--src', required=True)
    ap.add_argument('--out', required=True)
    args = ap.parse_args()
    src = open(args.src, encoding='utf-8').read()

    parts = ['/* constants copied from the module source */',
             grab_define_block(src),
             '',
             grab_enum(src, 'hdr_dm_packet_type'),
             '',
             PRELUDE,
             '/* module defaults for the injection patterns */',
             'static void hv_init_patterns(void)',
             '{',
             '\todd_pattern = DV_INJ_ODD_INJECTION;',
             '\teven_pattern = DV_INJ_EVEN_INJECTION;',
             '}',
             '']
    for fn in FUNCS:
        parts.append(grab_function(src, fn))
        parts.append('')
    parts.append(MAIN)

    text = '\n'.join(parts)
    with open(args.out, 'w', encoding='utf-8') as f:
        f.write(text)
    print('generated %s (%d bytes, %d functions)' % (args.out, len(text), len(FUNCS)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
